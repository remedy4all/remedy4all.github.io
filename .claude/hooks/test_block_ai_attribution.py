"""Tests for block-ai-attribution.py. Run: uv run --script .claude/hooks/test_block_ai_attribution.py"""

import json
import subprocess
import sys
import tempfile
from pathlib import Path

HOOK = Path(__file__).with_name("block-ai-attribution.py")


def run(command: str, tool: str = "Bash") -> int:
    payload = json.dumps({"tool_name": tool, "tool_input": {"command": command}})
    return subprocess.run(
        [sys.executable, str(HOOK)], input=payload, text=True, capture_output=True
    ).returncode


def main() -> int:
    with tempfile.TemporaryDirectory() as tmp:
        msg_file = Path(tmp) / "msg.txt"
        msg_file.write_text("Add site\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n", encoding="utf-8")
        clean_file = Path(tmp) / "clean.txt"
        clean_file.write_text("Add site\n", encoding="utf-8")

        cases = [
            ("trailer in -m", 'git commit -m "Add site" -m "Co-Authored-By: Claude Opus <noreply@anthropic.com>"', 2),
            ("heredoc generator line", "git commit -F - <<'EOF'\nAdd site\n\n🤖 Generated with Claude Code\nEOF", 2),
            ("powershell here-string", "git commit -m @'\nAdd site\n\nGenerated with Claude Code\n'@", 2),
            ("message file", f'git commit -F "{msg_file.as_posix()}"', 2),
            ("tag message", 'git tag -a v0.1.0 -m "v0.1.0 generated by Claude"', 2),
            ("git -C form", 'git -C repo commit -m "x" -m "Co-authored-by: GitHub Copilot <x@y>"', 2),
            ("mentions CLAUDE.md", 'git commit -m "Point CLAUDE.md at .claude/project.md"', 0),
            ("clean message file", f'git commit -F "{clean_file.as_posix()}"', 0),
            ("human co-author", 'git commit -m "x" -m "Co-Authored-By: Maria P <maria@example.org>"', 0),
            ("not a commit", 'echo "Co-Authored-By: Claude"', 0),
        ]
        failures = 0
        for name, command, expected in cases:
            got = run(command, "PowerShell" if "@'" in command else "Bash")
            ok = got == expected
            failures += not ok
            print(f"{'PASS' if ok else 'FAIL'}  {name}: exit {got}, expected {expected}")
    print(f"{len(cases) - failures}/{len(cases)} passed")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    raise SystemExit(main())
